"""Read an existing caption track and print timestamped text."""

from argparse import ArgumentParser
import os
from flashdata import FlashData
from _support import add_output, report_usage, run, save_json


def main(argv=None):
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("video_id", nargs="?", default="dQw4w9WgXcQ")
    parser.add_argument("--language", help="One code or comma-separated codes; omitted: en-orig, then en")
    parser.add_argument("--auto", action="store_true", help="Select automatic captions instead of uploaded captions")
    parser.add_argument("--segments", type=int, default=3, help="Number of segments to print; JSON export keeps all")
    add_output(parser)
    args = parser.parse_args(argv)
    if args.segments < 1:
        parser.error("--segments must be positive")
    params = {"auto": args.auto}
    if args.language is not None:
        params["language"] = args.language.split(",") if "," in args.language else args.language
    with FlashData(api_key=os.getenv("FLASHDATA_API_KEY")) as client:
        response = client.youtube.captions(args.video_id, **params)
    for result in response["results"]:
        for track in result.get("tracks", [result]):
            print(f"{track['languageCode']} | automatic={track['isAutoGenerated']}")
            for segment in track.get("segments", [])[: args.segments]:
                print(f"{segment['start']:.2f}–{segment['end']:.2f}: {segment['text']}")
        for error in result.get("errors", []):
            print(error["languageCode"], error["code"], error["message"])
    report_usage(response)
    save_json(response, args.output)


if __name__ == "__main__":
    run(main)
